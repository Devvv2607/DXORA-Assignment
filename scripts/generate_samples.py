    S.append(
        "## 500: unexpected error\n\n**Source: in-process (mocked)**. The posting service was replaced by one that raises; "
        "no stack trace or exception text reaches the client.\n\n" + inproc["500"]
    )
    S.append("## GET /platforms\n\n**Source: server** (no credentials configured).\n\n" + fmt(platforms))
    (ROOT / "docs" / "sample_responses.md").write_text("\n".join(S), encoding="utf-8")
    print("written docs/sample_requests.md and docs/sample_responses.md")


