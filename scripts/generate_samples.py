def fmt(resp: httpx.Response, show_headers: tuple[str, ...] = ()) -> str:
    try:
        body = json.dumps(resp.json(), indent=2, ensure_ascii=False)
    except ValueError:
        body = resp.text
    head = f"HTTP {resp.status_code}"
    for h in show_headers:
        if h in resp.headers:
            head += f"\n{h}: {resp.headers[h]}"
    return f"```http\n{head}\n```\n\n```json\n{body}\n```\n"


def server(method: str, path: str, *, json_body=None, content=None, headers=None) -> httpx.Response:
    h = {"Content-Type": "application/json", **(headers or {})}
    with httpx.Client(base_url=BASE, timeout=30) as c:
        return c.request(method, path, json=json_body, content=content, headers=h)


