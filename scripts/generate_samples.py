        "Invoke-WebRequest -Method Post -Uri http://localhost:4000/posting -ContentType 'application/json' -Body $body `\n"
        "  -Headers @{ 'Idempotency-Key' = 'docs-demo-001' } -UseBasicParsing |\n"
